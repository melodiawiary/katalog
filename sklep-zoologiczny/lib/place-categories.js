// 1 salon, 2-4 salony, 5+ salonów
export function countWord(cfg, n) {
  return n === 1 ? cfg.nounOne : n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 10 || n % 100 >= 20) ? cfg.nounFew : cfg.nounMany;
}

